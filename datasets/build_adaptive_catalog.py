def build():
    quiz_data = {}
    for path in [ROOT/'knowledge-project/quizzes.json', ROOT/'datasets/academy_demo/additional_quizzes.json']:
        quiz_data.update(json.loads(path.read_text(encoding='utf-8')))
    prerequisites = {'mat_01':[], 'mat_02':['mat_01'], 'mat_03':['mat_02'], 'mat_04':['mat_01']}
    result = {}
    for mid, entries in SKILLS.items():
        questions = quiz_data[mid]['questions']
        if len(entries) != len(questions):
            raise ValueError(f'Concept mapping incomplete: {mid} ({len(entries)} vs {len(questions)})')
        if mid not in prerequisites:
            prerequisites[mid] = [mid[:-2]+'01'] if mid.endswith('_02') else []
        result[mid] = {'prerequisites':prerequisites[mid], 'concepts':[
            {'question_id':question['id'], 'name':name, 'section':section, 'exercise':exercise}
            for question,(name,section,exercise) in zip(questions,entries)]}
    (ROOT/'learning-content/adaptive_catalog.json').write_text(json.dumps(result,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    print(json.dumps({'topics':len(result),'concepts':sum(len(item['concepts']) for item in result.values())}))


if __name__ == '__main__':
    build()
